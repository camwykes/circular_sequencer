// WAV encoding and zip packaging for exporting a multi-sampled keyboard.
// No dependencies: zip files are written uncompressed ("stored"), which is
// what most samplers expect anyway, since WAV audio barely compresses.

(function () {
  const NOTE_NAMES = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'];
  const noteName = m => NOTE_NAMES[m % 12] + (Math.floor(m / 12) - 1);

  // ---------- WAV ----------
  // channels: Float32Array[] (1 or 2), bitDepth: 16 | 24 | 32 (32 = float)
  // rootMidi is written into a 'smpl' chunk so samplers can auto-map the file.
  function encodeWav(channels, sampleRate, {bitDepth = 24, rootMidi = 60, gain = 1} = {}) {
    const numCh = channels.length;
    const frames = channels[0].length;
    const isFloat = bitDepth === 32;
    const bytesPerSample = bitDepth / 8;
    const blockAlign = numCh * bytesPerSample;
    const dataBytes = frames * blockAlign;

    const fmtSize = isFloat ? 18 : 16;
    const factSize = isFloat ? 12 : 0;      // 'fact' chunk, required for float WAVs
    const smplSize = 8 + 36;
    const headerBytes = 12 + (8 + fmtSize) + factSize + smplSize + 8;
    const buf = new ArrayBuffer(headerBytes + dataBytes);
    const v = new DataView(buf);
    let p = 0;
    const str = s => { for (let i = 0; i < s.length; i++) v.setUint8(p++, s.charCodeAt(i)); };
    const u32 = x => { v.setUint32(p, x, true); p += 4; };
    const u16 = x => { v.setUint16(p, x, true); p += 2; };

    str('RIFF'); u32(buf.byteLength - 8); str('WAVE');

    str('fmt '); u32(fmtSize);
    u16(isFloat ? 3 : 1); u16(numCh); u32(sampleRate);
    u32(sampleRate * blockAlign); u16(blockAlign); u16(bitDepth);
    if (isFloat) u16(0);

    if (isFloat) { str('fact'); u32(4); u32(frames); }

    str('smpl'); u32(36);
    u32(0); u32(0);                          // manufacturer, product
    u32(Math.round(1e9 / sampleRate));       // sample period in ns
    u32(rootMidi); u32(0);                   // MIDI unity note, pitch fraction
    u32(0); u32(0);                          // SMPTE format, offset
    u32(0); u32(0);                          // loop count, sampler data

    str('data'); u32(dataBytes);

    for (let i = 0; i < frames; i++) {
      for (let c = 0; c < numCh; c++) {
        let s = channels[c][i] * gain;
        if (isFloat) { v.setFloat32(p, s, true); p += 4; continue; }
        s = Math.max(-1, Math.min(1, s));
        if (bitDepth === 16) {
          v.setInt16(p, Math.round(s < 0 ? s * 32768 : s * 32767), true); p += 2;
        } else {
          const x = Math.round(s < 0 ? s * 8388608 : s * 8388607);
          v.setUint8(p++, x & 0xff); v.setUint8(p++, (x >> 8) & 0xff); v.setUint8(p++, (x >> 16) & 0xff);
        }
      }
    }
    return new Uint8Array(buf);
  }

  // ---------- SFZ ----------
  // A tiny mapping file: each sample plays only on its own key.
  function makeSfz(entries) {
    const lines = ['// Generated by Sample Keyboard', '<group>', 'amp_veltrack=100', ''];
    for (const e of entries) {
      lines.push(`<region> sample=${e.fileName} key=${e.midi} pitch_keycenter=${e.midi}`);
    }
    return new TextEncoder().encode(lines.join('\n') + '\n');
  }

  // ---------- ZIP (stored, no compression) ----------
  const CRC_TABLE = (() => {
    const t = new Uint32Array(256);
    for (let n = 0; n < 256; n++) {
      let c = n;
      for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
      t[n] = c >>> 0;
    }
    return t;
  })();
  function crc32(data) {
    let c = 0xffffffff;
    for (let i = 0; i < data.length; i++) c = CRC_TABLE[(c ^ data[i]) & 0xff] ^ (c >>> 8);
    return (c ^ 0xffffffff) >>> 0;
  }

  // files: [{name, data: Uint8Array}] -> Blob
  function makeZip(files) {
    const parts = [];
    const central = [];
    let offset = 0;
    const now = new Date();
    const dosTime = (now.getHours() << 11) | (now.getMinutes() << 5) | (now.getSeconds() >> 1);
    const dosDate = ((now.getFullYear() - 1980) << 9) | ((now.getMonth() + 1) << 5) | now.getDate();

    for (const f of files) {
      const name = new TextEncoder().encode(f.name);
      const crc = crc32(f.data);
      const size = f.data.length;

      const local = new DataView(new ArrayBuffer(30));
      local.setUint32(0, 0x04034b50, true);
      local.setUint16(4, 20, true);          // version needed
      local.setUint16(6, 0x0800, true);      // UTF-8 names
      local.setUint16(8, 0, true);           // stored
      local.setUint16(10, dosTime, true);
      local.setUint16(12, dosDate, true);
      local.setUint32(14, crc, true);
      local.setUint32(18, size, true);
      local.setUint32(22, size, true);
      local.setUint16(26, name.length, true);
      local.setUint16(28, 0, true);
      parts.push(local.buffer, name, f.data);

      const cen = new DataView(new ArrayBuffer(46));
      cen.setUint32(0, 0x02014b50, true);
      cen.setUint16(4, 20, true);
      cen.setUint16(6, 20, true);
      cen.setUint16(8, 0x0800, true);
      cen.setUint16(10, 0, true);
      cen.setUint16(12, dosTime, true);
      cen.setUint16(14, dosDate, true);
      cen.setUint32(16, crc, true);
      cen.setUint32(20, size, true);
      cen.setUint32(24, size, true);
      cen.setUint16(28, name.length, true);
      cen.setUint32(42, offset, true);
      central.push(cen.buffer, name);

      offset += 30 + name.length + size;
    }
    const centralSize = central.reduce((n, b) => n + b.byteLength, 0);
    const end = new DataView(new ArrayBuffer(22));
    end.setUint32(0, 0x06054b50, true);
    end.setUint16(8, files.length, true);
    end.setUint16(10, files.length, true);
    end.setUint32(12, centralSize, true);
    end.setUint32(16, offset, true);
    return new Blob([...parts, ...central, end.buffer], {type: 'application/zip'});
  }

  function download(blob, fileName) {
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = fileName;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 60000);
  }

  window.KeyboardExport = {encodeWav, makeSfz, makeZip, download, noteName};
})();
